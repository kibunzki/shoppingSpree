function parseAbbr(csvText) {
    const lines = csvText.trim().split('\n');
    const table = {}

    for (let i = 1; i < lines.length; i++) {
        const cols = lines[i].split(',');
        table[cols[0]] = cols[1]
    }

    return table
}

function parseMinWage(csvText) {
    const lines = csvText.trim().split('\n');
    const headers = lines[0].split(',');
    const states = headers.slice(1);
    const fgIndex = states.indexOf('FG');

    const byYear = {};
    const byState = {};
    const missingStates = ['AL', 'LA', 'SC', 'TN'];

    states.forEach(state => byState[state] = {});
    missingStates.forEach(state => byState[state] = {}); // initialize missing states

    for (let i = 0; i < lines.length; i++) {
        const cols = lines[i].split(',');
        const year = parseInt(cols[0].slice(0, 4));

        byYear[year] = {};

        const fgVal = cols[fgIndex + 1];
        const fgParsed = fgVal !== '' ? parseFloat(fgVal) : null;

        states.forEach((state, j) => {
            const val = cols[j + 1];
            const parsed = val !== '' ? parseFloat(val) : fgParsed;

            byYear[year][state] = parsed;
            byState[state][year] = parsed;
        });

        // copy FG values to missing states
        missingStates.forEach(state => {
            byYear[year][state] = fgParsed;
            byState[state][year] = fgParsed;
        });
    }

    return [byYear, byState];
}

function parseSeriesLookup(csvText) {
  const lines = csvText.trim().split('\n');
  const lookup = {};
  let order = {};

  for (let i = 1; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;

    // Find the first comma to split seriesID from the rest
    const commaIdx = line.indexOf(',');
    const id = line.slice(0, commaIdx).trim();
    let item = line.slice(commaIdx + 1).trim();

    // Strip surrounding quotes if present
    if (item.startsWith('"') && item.endsWith('"')) {
      item = item.slice(1, -1).trim();
    }

    lookup[id] = item;
    order[id] = i - 1;
  }

  return [lookup, order];
}

function parsePriceData(csvText) {
    const lines = csvText.trim().split('\n');
    const bySeriesYear = {};
    const bySeries = {};
    const lastValue = {}; // track last seen value per series

    for (let i = 1; i < lines.length; i++) {
        let [seriesID, year, value] = lines[i].split(',');
        seriesID = seriesID.slice(7)
        const parsedYear = parseInt(year);

        let parsedValue;
        if (value !== '' && value !== undefined) {
            parsedValue = parseFloat(value);
            lastValue[seriesID] = parsedValue; // update last seen
        } else {
            parsedValue = lastValue[seriesID] ?? null; // fall back to last seen
        }

        if (!bySeriesYear[seriesID]) bySeriesYear[seriesID] = {};
        bySeriesYear[seriesID][parsedYear] = parsedValue;

        if (!bySeries[seriesID]) bySeries[seriesID] = [];
        bySeries[seriesID].push({ year: parsedYear, value: parsedValue });
    }

    return [bySeriesYear, bySeries];
}

